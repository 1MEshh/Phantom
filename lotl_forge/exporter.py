"""Exporters for MITRE ATT&CK Navigator v4.5 layers, JSON telemetry logs, and Markdown reports."""

from __future__ import annotations

import datetime
import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

from lotl_forge.scanner import ScanReport
from lotl_forge.simulator import TelemetryRecord


def build_navigator_layer(
    scan_report: Optional[ScanReport] = None,
    telemetry_records: Optional[Sequence[TelemetryRecord]] = None,
    layer_name: str = "lotl-forge Dual-Use Binary Hardening & Telemetry Coverage",
) -> Dict[str, Any]:
    """Generate a MITRE ATT&CK Navigator v4.5 JSON layer from scan findings and/or telemetry records."""
    technique_map: Dict[str, Dict[str, Any]] = {}

    if scan_report is not None:
        platform_str = "Windows" if scan_report.scanned_os == "windows" else "Linux"
        for finding in scan_report.findings:
            if not finding.present:
                continue
            for tech_id in finding.mitre_techniques:
                entry = technique_map.setdefault(
                    tech_id,
                    {
                        "techniqueID": tech_id,
                        "score": 0,
                        "color": "",
                        "comment": [],
                        "enabled": True,
                        "metadata": [],
                    },
                )
                entry["score"] = max(entry["score"], min(100, finding.risk_score * 8))
                entry["comment"].append(
                    f"{finding.name} ({finding.severity}, path={finding.resolved_path or 'N/A'})"
                )
                entry["metadata"].append(
                    {"name": "binary", "value": finding.name}
                )
    else:
        platform_str = "Linux, Windows"

    if telemetry_records:
        for rec in telemetry_records:
            for tech_id in rec.mitre_techniques:
                entry = technique_map.setdefault(
                    tech_id,
                    {
                        "techniqueID": tech_id,
                        "score": 50,
                        "color": "",
                        "comment": [],
                        "enabled": True,
                        "metadata": [],
                    },
                )
                entry["score"] = max(entry["score"], 60)
                entry["comment"].append(
                    f"Telemetry verified for {rec.binary_name} [{rec.execution_mode}]"
                )

    techniques_list: List[Dict[str, Any]] = []
    for tech_id in sorted(technique_map.keys()):
        item = technique_map[tech_id]
        score = int(item["score"])
        if score >= 80:
            color = "#d73027"
        elif score >= 60:
            color = "#fc8d59"
        elif score >= 40:
            color = "#fee08b"
        else:
            color = "#91bfdb"
        techniques_list.append(
            {
                "techniqueID": tech_id,
                "score": score,
                "color": color,
                "comment": "; ".join(item["comment"]),
                "enabled": True,
                "metadata": item["metadata"],
            }
        )

    return {
        "name": layer_name,
        "versions": {
            "attack": "15",
            "navigator": "4.9.1",
            "layer": "4.5",
        },
        "domain": "enterprise-attack",
        "description": (
            "Automated dual-use administrative binary posture and SIEM telemetry "
            "coverage layer generated by lotl-forge."
        ),
        "filters": {
            "platforms": [p.strip() for p in platform_str.split(",")],
        },
        "sorting": 3,
        "layout": {
            "layout": "side",
            "aggregateFunction": "average",
            "showID": True,
            "showName": True,
        },
        "hideDisabled": False,
        "techniques": techniques_list,
        "gradient": {
            "colors": ["#91bfdb", "#fee08b", "#fc8d59", "#d73027"],
            "minValue": 0,
            "maxValue": 100,
        },
    }


def export_navigator_layer(
    output_path: str | Path,
    scan_report: Optional[ScanReport] = None,
    telemetry_records: Optional[Sequence[TelemetryRecord]] = None,
) -> Path:
    """Write MITRE ATT&CK Navigator v4.5 JSON layer to disk."""
    dest = Path(output_path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    layer = build_navigator_layer(scan_report=scan_report, telemetry_records=telemetry_records)
    dest.write_text(json.dumps(layer, indent=2) + "\n", encoding="utf-8")
    return dest


def export_json_audit(
    output_path: str | Path,
    scan_report: Optional[ScanReport] = None,
    telemetry_records: Optional[Sequence[TelemetryRecord]] = None,
) -> Path:
    """Write full JSON posture report and/or telemetry audit records to disk."""
    dest = Path(output_path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    payload: Dict[str, Any] = {
        "schema_version": "1.0",
        "generated_at_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "tool": "lotl-forge",
    }
    if scan_report is not None:
        payload["scan_report"] = scan_report.to_dict()
    if telemetry_records is not None:
        payload["telemetry_records"] = [r.to_dict() for r in telemetry_records]
    dest.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return dest


def render_markdown_report(
    scan_report: Optional[ScanReport] = None,
    telemetry_records: Optional[Sequence[TelemetryRecord]] = None,
) -> str:
    """Render a comprehensive Markdown Purple-Team Hardening & Telemetry Debrief Report."""
    lines: List[str] = [
        "# Endpoint Dual-Use Binary Hardening & Telemetry Audit Report",
        "",
        f"- **Generated UTC**: `{datetime.datetime.now(datetime.timezone.utc).isoformat()}`",
        "- **Generator**: `lotl-forge v1.0.0`",
        "",
    ]

    if scan_report is not None:
        lines.extend(
            [
                "## 1. Executive Posture Summary",
                "",
                "| Metric | Value |",
                "| :--- | :--- |",
                f"| Hostname | `{scan_report.hostname}` |",
                f"| Target Operating System | `{scan_report.scanned_os}` |",
                f"| Scan Mode | `{scan_report.scan_mode}` |",
                f"| **Host Hardening Score** | **{scan_report.hardening_score} / 100** |",
                f"| **Host LOTL Exposure Score** | **{scan_report.exposure_score} / 100** (`{scan_report.risk_rating}`) |",
                f"| Catalog Utilities Present | `{scan_report.present_count} / {scan_report.total_catalog_checked}` |",
                f"| High/Critical Risk Findings | `{scan_report.high_risk_count}` |",
                f"| Writable PATH Directories | `{len(scan_report.writable_path_dirs)}` |",
                "",
                "## 2. Binary Posture Findings",
                "",
                "| Binary | Present | Severity | Risk Score | Path | SUID/SGID | MITRE ATT&CK |",
                "| :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
            ]
        )
        for finding in scan_report.findings:
            suid_str = "SUID" if finding.suid_bit else ("SGID" if finding.sgid_bit else "None")
            path_str = f"`{finding.resolved_path}`" if finding.resolved_path else "-"
            tech_str = ", ".join(f"`{t}`" for t in finding.mitre_techniques)
            lines.append(
                f"| `{finding.name}` | {'Yes' if finding.present else 'No'} | "
                f"**{finding.severity}** | {finding.risk_score} | {path_str} | {suid_str} | {tech_str} |"
            )

        lines.extend(
            [
                "",
                "## 3. Prioritized Hardening & Remediation Checklist",
                "",
            ]
        )
        if scan_report.remediation_plan:
            for idx, step in enumerate(scan_report.remediation_plan, start=1):
                lines.append(f"{idx}. {step}")
        else:
            lines.append("1. No high-priority remediation actions identified.")
        lines.append("")

    if telemetry_records:
        lines.extend(
            [
                "## 4. SIEM Telemetry Verification Audit Log",
                "",
                "| Binary | Mode | PID / PPID | Exit Code | MITRE ATT&CK | Log Channel | HMAC-SHA256 (Prefix) |",
                "| :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
            ]
        )
        for rec in telemetry_records:
            pid_str = f"{rec.pid or 'N/A'} / {rec.ppid}"
            tech_str = ", ".join(f"`{t}`" for t in rec.mitre_techniques)
            lines.append(
                f"| `{rec.binary_name}` | `{rec.execution_mode}` | `{pid_str}` | "
                f"`{rec.exit_code}` | {tech_str} | `{rec.expected_log_source}` | `{rec.record_hmac_sha256[:16]}...` |"
            )
        lines.append("")

    return "\n".join(lines)


def export_markdown_report(
    output_path: str | Path,
    scan_report: Optional[ScanReport] = None,
    telemetry_records: Optional[Sequence[TelemetryRecord]] = None,
) -> Path:
    """Write Markdown hardening and telemetry report to disk."""
    dest = Path(output_path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    content = render_markdown_report(scan_report=scan_report, telemetry_records=telemetry_records)
    dest.write_text(content, encoding="utf-8")
    return dest
